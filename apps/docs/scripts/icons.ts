// Downloads the icons the docs use and writes them to icons.ts as inline SVG strings, so they take
// the page's `currentColor` (an <img> can't). Run from apps/docs: `bun scripts/icons.ts`.
//
// - Solar icons, bold duotone, by 480 Design (CC BY 4.0): https://www.figma.com/community/file/1166831539721848736,
//   from @iconify-json/solar
// - Simple Icons brand logos (CC0): https://simpleicons.org
// - The OpenAI mark from Hugeicons (MIT), since Simple Icons no longer carries it
// The brand logos are trademarks of their owners, used here only to name the tools they stand for.
//
// Icon data is parsed, never executed.

const SOLAR = "https://unpkg.com/@iconify-json/solar@1.2.17/icons.json";
const HUGEICONS = "https://unpkg.com/@hugeicons/core-free-icons@4.4.0/dist/esm";
const SIMPLE_ICONS = "https://unpkg.com/simple-icons@16.38.1/icons";

/** Name in icons.ts → Solar icon name (bold duotone). */
const solar = {
  home: "home-2-bold-duotone",
  bolt: "bolt-bold-duotone",
  api: "code-square-bold-duotone",
  terminal: "file-terminal-bold-duotone",
  server: "server-square-bold-duotone",
  book: "book-2-bold-duotone",
  bot: "bot-bold-duotone",
} as const;

/** Name in icons.ts → Hugeicons export name. */
const hugeicons = {
  openai: "ChatGptIcon",
} as const;

/** Name in icons.ts → Simple Icons slug. */
const brands = {
  claudeCode: "claudecode",
  cursor: "cursor",
} as const;

async function download(url: string): Promise<string> {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.text();
}

/** A Hugeicons module (`const X = [["path", { d: "…", … }], …]`) as an SVG string. */
function hugeiconSvg(source: string, name: string): string {
  const literal = /=\s*(\[[\s\S]*\]);/.exec(source)?.[1];
  if (!literal) throw new Error(`${name}: unexpected module shape`);
  // Quote the object keys so the array literal parses as JSON.
  const elements = JSON.parse(literal.replace(/([{,]\s*)([A-Za-z]+):/g, '$1"$2":')) as [
    string,
    Record<string, string>,
  ][];
  const body = elements
    .map(([tag, attributes]) => {
      const pairs = Object.entries(attributes)
        .filter(([attribute]) => attribute !== "key")
        .map(([attribute, value]) => {
          const kebab = attribute.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
          return `${kebab}="${value}"`;
        });
      return `<${tag} ${pairs.join(" ")}/>`;
    })
    .join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24" fill="none">${body}</svg>`;
}

/** A Simple Icons SVG, filled with currentColor and without its <title>. */
function brandSvg(source: string, slug: string): string {
  const path = /<path d="([^"]+)"/.exec(source)?.[1];
  if (!path) throw new Error(`${slug}: unexpected SVG shape`);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24" fill="currentColor"><path d="${path}"/></svg>`;
}

/** An Iconify icon set entry (`{ body }`, sized by the set) as an SVG string. */
function iconifySvg(
  set: { icons: Record<string, { body: string }>; width?: number; height?: number },
  name: string,
): string {
  const icon = set.icons[name];
  if (!icon) throw new Error(`Solar has no icon named ${name}`);
  const width = set.width ?? 24;
  const height = set.height ?? 24;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="24" height="24">${icon.body}</svg>`;
}

const icons: Record<string, string> = {};
const solarSet = JSON.parse(await download(SOLAR));
for (const [name, icon] of Object.entries(solar)) {
  icons[name] = iconifySvg(solarSet, icon);
}
for (const [name, icon] of Object.entries(hugeicons)) {
  icons[name] = hugeiconSvg(await download(`${HUGEICONS}/${icon}.js`), icon);
}
for (const [name, slug] of Object.entries(brands)) {
  icons[name] = brandSvg(await download(`${SIMPLE_ICONS}/${slug}.svg`), slug);
}

const output = `// Generated by scripts/icons.ts; edit that script and run \`bun scripts/icons.ts\` instead.
// Solar icons by 480 Design (CC BY 4.0), Simple Icons brand logos (CC0) and the Hugeicons OpenAI
// mark (MIT). Brand logos are trademarks of their owners.
export const icons = ${JSON.stringify(icons, null, 2)} as const;
`;
await Bun.write(new URL("../icons.ts", import.meta.url), output);
console.log(`Wrote ${Object.keys(icons).length} icons to icons.ts`);
